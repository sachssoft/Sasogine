namespace Sachssoft.Engine.Components.Models;

/// <summary>
/// Provides category names used to organize model properties,
/// components, and settings by their functional purpose.
/// </summary>
public static class Categories
{
    /// <summary>
    /// Contains properties related to the game world, world structure,
    /// dimensions, coordinates, and world-level configuration.
    /// </summary>
    public const string World = "World";

    /// <summary>
    /// Contains properties related to gameplay mechanics,
    /// interactions, progression, and game-specific functionality.
    /// </summary>
    public const string Gameplay = "Gameplay";

    /// <summary>
    /// Contains properties that define rules, restrictions,
    /// conditions, requirements, and constraints.
    /// </summary>
    public const string Rules = "Rules";

    /// <summary>
    /// Contains properties that modify or influence existing values,
    /// states, characteristics, or behavior.
    /// </summary>
    public const string Modifiers = "Modifiers";

    /// <summary>
    /// Contains commonly used and general-purpose properties that
    /// do not require a more specialized category.
    /// </summary>
    public const string Common = "Common";

    /// <summary>
    /// Contains descriptive information and metadata associated
    /// with an object, component, document, or resource.
    /// </summary>
    public const string Metadata = "Metadata";

    /// <summary>
    /// Contains properties related to scenery objects,
    /// decorations, and environmental visual elements.
    /// </summary>
    public const string Scenery = "Scenery";

    /// <summary>
    /// Contains properties related to parallax layers,
    /// scrolling, movement factors, and depth effects.
    /// </summary>
    public const string Parallaxes = "Parallaxes";

    /// <summary>
    /// Contains properties related to grids, cells, spacing,
    /// alignment, and grid-based positioning.
    /// </summary>
    public const string Grid = "Grid";

    /// <summary>
    /// Contains properties related to viewing, cameras,
    /// visibility, viewport behavior, and presentation.
    /// </summary>
    public const string View = "View";

    /// <summary>
    /// Contains properties related to editor workspaces,
    /// working areas, workspace state, and configuration.
    /// </summary>
    public const string Workspace = "Workspace";

    /// <summary>
    /// Contains properties used for diagnostics, debugging,
    /// development information, and visualization of internal state.
    /// </summary>
    public const string Debug = "Debug";

    /// <summary>
    /// Contains properties related to rendering, drawing,
    /// graphical output, and rendering configuration.
    /// </summary>
    public const string Rendering = "Rendering";

    /// <summary>
    /// Contains properties related to sound, music,
    /// playback, volume, and other audio behavior.
    /// </summary>
    public const string Audio = "Audio";

    /// <summary>
    /// Contains properties related to spatial transformations,
    /// including position, rotation, scale, and offsets.
    /// </summary>
    public const string Transform = "Transform";

    /// <summary>
    /// Contains miscellaneous properties that do not fit into
    /// another established functional category.
    /// </summary>
    public const string Miscelleaneous = "Miscelleaneous";

    /// <summary>
    /// Contains properties related to assets, resources,
    /// references, loading, and asset configuration.
    /// </summary>
    public const string Assets = "Assets";

    /// <summary>
    /// Contains properties that define the visual appearance,
    /// styling, presentation, and visual characteristics of an object.
    /// </summary>
    public const string Appearance = "Appearance";

    /// <summary>
    /// Contains properties related to physical simulation,
    /// forces, movement, mass, and other physical characteristics.
    /// </summary>
    public const string Physics = "Physics";

    /// <summary>
    /// Contains properties related to animations, timing,
    /// playback, transitions, and animated state.
    /// </summary>
    public const string Animation = "Animation";

    /// <summary>
    /// Contains properties related to collision detection,
    /// collision geometry, collision filtering, and responses.
    /// </summary>
    public const string Collision = "Collision";

    /// <summary>
    /// Contains properties related to user input,
    /// controls, bindings, devices, and input handling.
    /// </summary>
    public const string Input = "Input";

    /// <summary>
    /// Contains properties related to network communication,
    /// synchronization, connectivity, and multiplayer functionality.
    /// </summary>
    public const string Networking = "Networking";

    /// <summary>
    /// Contains properties related to environmental atmosphere,
    /// ambient conditions, weather, and atmospheric effects.
    /// </summary>
    public const string Atmosphere = "Atmosphere";

    /// <summary>
    /// Contains properties related to design-time configuration,
    /// composition, structure, and object design.
    /// </summary>
    public const string Design = "Design";

    /// <summary>
    /// Contains properties related to sketches, guides,
    /// construction geometry, and preliminary design information.
    /// </summary>
    public const string Sketch = "Sketch";

    /// <summary>
    /// Contains properties that define runtime behavior,
    /// actions, reactions, state changes, and behavioral configuration.
    /// </summary>
    public const string Behavior = "Behavior";

    /// <summary>
    /// Contains properties related to editing, editor interaction,
    /// manipulation, and editable state.
    /// </summary>
    public const string Edit = "Edit";
}