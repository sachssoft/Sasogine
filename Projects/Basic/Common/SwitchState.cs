namespace Sachssoft.Sasogine.Common
{
    /// <summary>
    /// Represents a binary switch state.
    /// </summary>
    public enum SwitchState
    {
        /// <summary>
        /// The switch is disabled or inactive.
        /// </summary>
        Off = 0,

        /// <summary>
        /// The switch is enabled or active.
        /// </summary>
        On = 1
    }
}