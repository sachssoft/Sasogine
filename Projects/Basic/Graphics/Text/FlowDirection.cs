namespace Sachssoft.Sasogine.Graphics.Text
{
    /// <summary>
    /// Specifies the direction in which text content flows along an axis.
    /// </summary>
    public enum FlowDirection
    {
        /// <summary>
        /// Text flows from the near side toward the far side.
        /// </summary>
        NearToFar,

        /// <summary>
        /// Text flows from the far side toward the near side.
        /// </summary>
        FarToNear
    }
}