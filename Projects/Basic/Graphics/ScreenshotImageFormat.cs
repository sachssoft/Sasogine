namespace Sachssoft.Sasogine.Graphics;

/// <summary>
/// Specifies the image format used when encoding a screenshot.
/// </summary>
public enum ScreenshotImageFormat
{
    /// <summary>
    /// Encodes the screenshot using the Portable Network Graphics (PNG) format.
    /// </summary>
    PNG = 0,

    /// <summary>
    /// Encodes the screenshot using the JPEG (JPG) format.
    /// </summary>
    JPG = 1
}