namespace Sachssoft.Sasogine.Input
{
    /// <summary>
    /// Specifies the direction of a mouse wheel input.
    /// </summary>
    public enum MouseWheelState
    {
        /// <summary>
        /// No mouse wheel movement.
        /// </summary>
        None = 0,

        /// <summary>
        /// The mouse wheel moved upward.
        /// </summary>
        Up = 1,

        /// <summary>
        /// The mouse wheel moved downward.
        /// </summary>
        Down = 2
    }
}