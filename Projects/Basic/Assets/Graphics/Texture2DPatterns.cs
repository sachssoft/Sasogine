namespace Sachssoft.Sasogine.Assets.Graphics;

/// <summary>
/// Specifies how a texture is mapped to a target area.
/// </summary>
public enum Texture2DPattern
{
    /// <summary>
    /// Stretches the texture to fill the target area.
    /// </summary>
    Stretch,

    /// <summary>
    /// Repeats the texture across the target area.
    /// </summary>
    Repeat
}