namespace Sachssoft.Engine.Geometry;

/// <summary>
/// Specifies one of the four cardinal directions used to represent
/// the facing orientation of a rotation.
/// </summary>
public enum RotationFacing
{
    /// <summary>
    /// Represents an upward-facing orientation.
    /// </summary>
    Up,

    /// <summary>
    /// Represents a left-facing orientation.
    /// </summary>
    Left,

    /// <summary>
    /// Represents a downward-facing orientation.
    /// </summary>
    Down,

    /// <summary>
    /// Represents a right-facing orientation.
    /// </summary>
    Right
}