namespace Sachssoft.Engine.Controls;
/// <summary>Positions an icon relative to the value in an IconValueDisplay.</summary>
public enum IconPlacement
{
    /// <summary>Places the icon to the left of the value.</summary>
    Left,
    /// <summary>Places the icon to the right of the value.</summary>
    Right,
    /// <summary>Places the icon above the value.</summary>
    Top,
    /// <summary>Places the icon below the value.</summary>
    Bottom
}
