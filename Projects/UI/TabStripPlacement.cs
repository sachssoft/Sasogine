namespace Sachssoft.Engine.Controls;
/// <summary>Specifies the edge on which a tab control presents its header strip.</summary>
public enum TabStripPlacement
{
    /// <summary>Places a horizontal header strip above the selected page.</summary>
    Top,
    /// <summary>Places a vertical header strip to the left of the selected page.</summary>
    Left,
    /// <summary>Places a horizontal header strip below the selected page.</summary>
    Bottom,
    /// <summary>Places a vertical header strip to the right of the selected page.</summary>
    Right
}
