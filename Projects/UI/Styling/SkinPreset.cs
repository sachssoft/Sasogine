namespace Sachssoft.Engine.Controls.Styling;

/// <summary>
/// Identifies a skin embedded in the Controls assembly.
/// </summary>
public enum SkinPreset
{
    /// <summary>Uses the Sachssoft dark skin.</summary>
    SachssoftDark,

    /// <summary>Uses the Sachssoft light skin.</summary>
    SachssoftLight,

    /// <summary>Uses the Sachssoft modern skin.</summary>
    SachssoftModern,

    /// <summary>Uses the Sachssoft futuristic skin.</summary>
    SachssoftFuturistic,

    /// <summary>Uses the Sachssoft medieval skin.</summary>
    SachssoftMedieval,

    /// <summary>Uses the default workspace skin, currently Sachssoft Dark.</summary>
    Default
}
